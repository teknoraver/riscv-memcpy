#!/usr/bin/env python3
"""Generate memcpy_shifted*.S from glibc's sysdeps/riscv/multiarch/memcpy_shifted.S.

usage: gen.py [path/to/glibc/sysdeps/riscv/multiarch/memcpy_shifted.S]

memcpy_shifted.S       glibc code as is
memcpy_shifted_bl2.S   byte loop copies 2 bytes per iteration
memcpy_shifted_bits.S  no loops below 16 bytes: copy 8/4/2/1 bytes depending
                       on the bits of LEN, same for the DEST alignment head
memcpy_shifted_jt.S    computed jump into 15 unrolled byte copies, head as bits

All entries are aligned to 64 bytes so that only the code differs.
"""
import os, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    "~/src/glibc/sysdeps/riscv/multiarch/memcpy_shifted.S")
glibc = open(src).read()
body = re.search(r"^ENTRY \(__memcpy_shifted\)\n(.*)^END \(__memcpy_shifted\)",
                 glibc, re.S | re.M).group(1)

HEAD = """\
	beqz	a3, L(dst_aligned)
	sub	a2, a2, a3
	add	a4, a6, a3
	.p2align 4
L(align_loop):
	lbu	a5, 0(a1)
	addi	a1, a1, 1
	sb	a5, 0(a6)
	addi	a6, a6, 1
	bne	a6, a4, L(align_loop)
"""

BYTE_COPY = """\
L(byte_copy):
	beqz	a2, L(ret)
	add	a7, a6, a2
	.p2align 4
L(byte_loop):
	lbu	a3, 0(a1)
	addi	a1, a1, 1
	sb	a3, 0(a6)
	addi	a6, a6, 1
	bne	a6, a7, L(byte_loop)
L(ret):
	ret
"""

# The variants patch the byte loops of the glibc code as of fbcb359b5c; once
# glibc has other code there only memcpy_shifted.S is regenerated.
patchable = body.count(HEAD) == 1 and body.count(BYTE_COPY) == 1


def copy(n, regs=("a3", "a4", "a5", "a7")):
    """Copy N bytes (N <= 4 per group) at 0(a1) to 0(a6), then advance."""
    out = []
    for g in range(0, n, 4):
        k = min(4, n - g)
        out += [f"\tlbu\t{regs[i]}, {g + i}(a1)" for i in range(k)]
        out += [f"\tsb\t{regs[i]}, {g + i}(a6)" for i in range(k)]
    out += [f"\taddi\ta1, a1, {n}", f"\taddi\ta6, a6, {n}"]
    return "\n".join(out) + "\n"


BL2 = """\
L(byte_copy):
	/* Copy an odd byte first, then 2 bytes per iteration.  */
	andi	a3, a2, 1
	beqz	a3, 1f
	lbu	a3, 0(a1)
	addi	a1, a1, 1
	sb	a3, 0(a6)
	addi	a6, a6, 1
1:
	andi	a2, a2, -2
	beqz	a2, L(ret)
	add	a7, a6, a2
	.p2align 4
L(byte_loop):
	lbu	a3, 0(a1)
	lbu	a4, 1(a1)
	addi	a1, a1, 2
	sb	a3, 0(a6)
	sb	a4, 1(a6)
	addi	a6, a6, 2
	bne	a6, a7, L(byte_loop)
L(ret):
	ret
"""

# 0 < a3 < 8 bytes to align DEST; a4, a5, t0, t1 are free.
BITS_HEAD = ("""\
	beqz	a3, L(dst_aligned)
	sub	a2, a2, a3
	/* Copy 1, 2 and 4 bytes depending on the bits of the count.  */
	andi	a4, a3, 1
	beqz	a4, 1f
""" + copy(1, ("a5",)) + """\
1:
	andi	a4, a3, 2
	beqz	a4, 2f
""" + copy(2, ("a4", "a5")) + """\
2:
	andi	a4, a3, 4
	beqz	a4, L(dst_aligned)
""" + copy(4, ("a4", "a5", "t0", "t1")))

# 0 <= a2 < 16.
BITS = ("""\
L(byte_copy):
	/* Copy 8, 4, 2 and 1 bytes depending on the bits of LEN.  */
	andi	a3, a2, 8
	beqz	a3, 1f
""" + copy(8) + """\
1:
	andi	a3, a2, 4
	beqz	a3, 2f
""" + copy(4) + """\
2:
	andi	a3, a2, 2
	beqz	a3, 3f
""" + copy(2) + """\
3:
	andi	a3, a2, 1
	beqz	a3, L(ret)
	lbu	a3, 0(a1)
	sb	a3, 0(a6)
L(ret):
	ret
""")

# 0 <= a2 < 16: jump to the copy of byte LEN from the end.  Each lbu/sb
# pair is 8 bytes, compression is disabled to keep it so.
JT = ("""\
L(byte_copy):
	add	a1, a1, a2
	add	a6, a6, a2
	slli	a3, a2, 3
	lla	a4, L(jt_end)
	sub	a4, a4, a3
	jr	a4
	.option push
	.option norvc
""" + "".join(f"\tlbu\ta3, -{i}(a1)\n\tsb\ta3, -{i}(a6)\n" for i in range(15, 0, -1)) + """\
	.option pop
L(jt_end):
L(ret):
	ret
""")

PROLOGUE = """\
/* SPDX-License-Identifier: LGPL-2.1-or-later */
/*
 * Generated by gen.py from glibc's sysdeps/riscv/multiarch/memcpy_shifted.S.
 * {desc}
 */

#define SZREG		8
#define REG_L		ld
#define REG_S		sd
#define L(x)		.L##x
#define BLOCK_SIZE	(16 * SZREG)

	.text
	.globl	{name}
	.type	{name}, @function
	.p2align 6
{name}:
"""

variants = {
    "memcpy_shifted": ("glibc code as is.", body),
    "memcpy_shifted_bl2": ("Variant: byte loop copies 2 bytes per iteration.",
                           body.replace(BYTE_COPY, BL2)),
    "memcpy_shifted_bits": ("Variant: 8/4/2/1 byte blocks instead of byte loops below 16 bytes and in the DEST alignment head.",
                            body.replace(BYTE_COPY, BITS).replace(HEAD, BITS_HEAD)),
    "memcpy_shifted_jt": ("Variant: computed jump into unrolled byte copies below 16 bytes, head as in bits.",
                          body.replace(BYTE_COPY, JT).replace(HEAD, BITS_HEAD)),
}

if not patchable:
    variants = {"memcpy_shifted": variants["memcpy_shifted"]}

# Shifted loop unrolled to 8 words.  BODY4 is the 4 word loop body without
# the pointer increments; the carry word is in a4 before and after it.
LOOP4 = re.search(r"\tandi\tt4, a2, -\(4\*SZREG\)\n.*?^L\(shifted_word\):\n",
                  body, re.S | re.M)
if LOOP4:
    BODY4 = re.search(r"^L\(shifted_loop4\):\n(.*)\tbne\ta6, t4, L\(shifted_loop4\)\n",
                      LOOP4.group(0), re.S | re.M).group(1)
    BODY4 = "".join(l + "\n" for l in BODY4.splitlines()
                    if not re.match(r"\taddi\ta[16], a[16], 4\*SZREG", l))

    def body4(words):
        """BODY4 with SRC and DEST offsets moved by WORDS words."""
        def fix(m):
            n = int(m.group(1) or 1) if m.group(2) else 0
            return f"({n + words}*SZREG)("
        return re.sub(r"(?:\(?(\d*)\*?(SZREG)\)?|\b0)\((?=a[16]\))", fix, BODY4)

    STEP = lambda n: f"\taddi\ta1, a1, {n}*SZREG\n\taddi\ta6, a6, {n}*SZREG\n"
    LOOP8 = ("""\
	andi	t4, a2, -(8*SZREG)
	add	t4, a6, t4
	/* a4 = the current aligned source word.  */
	REG_L	a4, 0(a1)
	beq	a6, t4, L(shifted_4)
	.p2align 4
L(shifted_loop8):
""" + body4(0) + body4(4) + STEP(8) + """\
	bne	a6, t4, L(shifted_loop8)
L(shifted_4):
""")
    BLOCK4 = ("""\
	andi	t4, a2, 4*SZREG
	beqz	t4, L(shifted_word)
""" + body4(0) + STEP(4))
    variants["memcpy_shifted_u8"] = (
        "Variant: shifted loop copies 8 words per iteration, then one 4 word block.",
        body.replace(LOOP4.group(0), LOOP8 + BLOCK4 + "L(shifted_word):\n"))
    # Hybrid: below THR bytes the 4 word loop as is; from THR an out of line
    # 8 word loop first, then back to the 4 word loop.  a3 (SRC & 7) is free
    # in the loops: it is restored from t5 before going back.
    for thr in (256, 512):
        ent = re.search(r"\tREG_L\ta4, 0\(a1\)\n\tbeq\ta6, t4, L\(shifted_word\)\n", body).group(0)
        code = body.replace(ent, f"""\
	REG_L	a4, 0(a1)
	li	t3, {thr}
	bgeu	a2, t3, L(shifted_big)
L(shifted_4check):
	beq	a6, t4, L(shifted_word)
""")
        code = code.replace("L(ret):\n\tret\n", "L(ret):\n\tret\n" + f"""\
L(shifted_big):
	andi	a3, a2, -(8*SZREG)
	add	a3, a6, a3
	.p2align 4
L(shifted_loop8):
""" + body4(0) + body4(4) + STEP(8) + """\
	bne	a6, a3, L(shifted_loop8)
	srli	a3, t5, 3
	j	L(shifted_4check)
""")
        variants[f"memcpy_shifted_h{thr}"] = (
            f"Variant: from {thr} bytes an out of line 8 word shifted loop, then the 4 word loop.",
            code)
    variants["memcpy_shifted_u8n"] = (
        "Variant: shifted loop copies 8 words per iteration, then the word loop.",
        body.replace(LOOP4.group(0), LOOP8 + "L(shifted_word):\n"))

# Loads grouped before the stores, on the glibc code with the 8 word shifted
# loop: gb = aligned block loop as 8 loads + 8 stores twice, gs = shifted
# loop as 4 loads + 4 merges + 4 stores twice, g = both.
BLOCK_LOOP = re.search(r"^L\(block_loop\):\n.*?\tbne\ta6, a7, L\(block_loop\)\n",
                       body, re.S | re.M)
SHIFTED_LOOP8 = re.search(r"^L\(shifted_loop8\):\n.*?\tbne\ta6, t4, L\(shifted_loop8\)\n",
                          body, re.S | re.M)
if BLOCK_LOOP and SHIFTED_LOOP8:
    R8 = ("a3", "a4", "a5", "t0", "t1", "t2", "t3", "t4")
    gb = "L(block_loop):\n"
    for h in (0, 8):
        gb += "".join(f"\tREG_L\t{r}, ({h + i}*SZREG)(a1)\n" for i, r in enumerate(R8))
        gb += "".join(f"\tREG_S\t{r}, ({h + i}*SZREG)(a6)\n" for i, r in enumerate(R8))
    gb += ("\taddi\ta1, a1, BLOCK_SIZE\n\taddi\ta6, a6, BLOCK_SIZE\n"
           "\tbne\ta6, a7, L(block_loop)\n")

    def group(base, regs):
        """REGS[0] holds word BASE; load words BASE+1..BASE+4 into REGS[1:],
        merge, store words BASE..BASE+3.  The next carry ends in REGS[4]."""
        s = "".join(f"\tREG_L\t{r}, ({base + i + 1}*SZREG)(a1)\n" for i, r in enumerate(regs[1:]))
        for i in range(4):
            s += (f"\tsrl\t{regs[i]}, {regs[i]}, t5\n\tsll\ta5, {regs[i + 1]}, t6\n"
                  f"\tor\t{regs[i]}, {regs[i]}, a5\n")
        s += "".join(f"\tREG_S\t{r}, ({base + i}*SZREG)(a6)\n" for i, r in enumerate(regs[:4]))
        return s
    gs = ("L(shifted_loop8):\n" + group(0, ("a4", "t0", "t1", "t2", "t3")) +
          group(4, ("t3", "a4", "t0", "t1", "t2")) +
          "\tmv\ta4, t2\n\taddi\ta1, a1, 8*SZREG\n\taddi\ta6, a6, 8*SZREG\n"
          "\tbne\ta6, t4, L(shifted_loop8)\n")
    variants["memcpy_shifted_gb"] = (
        "Variant: aligned block loop as 8 loads then 8 stores, twice.",
        body.replace(BLOCK_LOOP.group(0), gb))
    variants["memcpy_shifted_gs"] = (
        "Variant: 8 word shifted loop as 4 loads, 4 merges, 4 stores, twice.",
        body.replace(SHIFTED_LOOP8.group(0), gs))
    variants["memcpy_shifted_g"] = (
        "Variant: both gb and gs.",
        body.replace(BLOCK_LOOP.group(0), gb).replace(SHIFTED_LOOP8.group(0), gs))

for name, (desc, code) in variants.items():
    with open(f"{name}.S", "w") as f:
        f.write(PROLOGUE.format(name=name, desc=desc) + code +
                f"\t.size\t{name}, .-{name}\n")
    print(f"{name}.S")
